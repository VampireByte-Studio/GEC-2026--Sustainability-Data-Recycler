package org.gec.gec2026sustainabilitydatarecycler.functions;

public class README_Data {
    String title;
    String DOI;

    int num_Var;
    int num_Case;

    String decription_of_data;
    int date_of_collection;
    String geographic_location;
    String funding_info;

    public String getTitle() {
        return title;
    }
    public void setTitle(String title) {
        this.title = title;
    }
    public String getDOI() {
        return DOI;
    }
    public void setDOI(String DOI) {
        this.DOI = DOI;
    }

    public int getNum_Var() {
        return num_Var;
    }
    public void setNum_Var(int num_Var) {
        this.num_Var = num_Var;
    }
    public int getNum_Case() {
        return num_Case;
    }
    public void setNum_Case(int num_Case) {
        this.num_Case = num_Case;
    }

    public String getDecription_of_data() {
        return decription_of_data;
    }
    public void setDecription_of_data(String decription_of_data) {
        this.decription_of_data = decription_of_data;
    }
    public int getDate_of_collection() {
        return date_of_collection;
    }
    public void setDate_of_collection(int date_of_collection) {
        this.date_of_collection = date_of_collection;
    }
    public String getGeographic_location() {
        return geographic_location;
    }
    public void setGeographic_location(String geographic_location) {
        this.geographic_location = geographic_location;
    }
    public String getFunding_info() {
        return funding_info;
    }
    public void setFunding_info(String funding_info) {
        this.funding_info = funding_info;
    }
}
